// Regenerate shared/stars-catalog.js from the published d3-celestial star table.
//
//   node scripts/gen-stars-catalog.mjs            # fetch and rewrite the module
//   node scripts/gen-stars-catalog.mjs --check    # fail when the file is stale
//
// Why a generated table instead of fetching at runtime: the skin must make no
// network requests. The source file is 640 KB of GeoJSON; this module keeps the
// four numbers the renderer needs and drops everything else.
//
// Source: https://cdn.jsdelivr.net/npm/d3-celestial@0.7.35/data/stars.6.json
// Licence: CC BY-SA 4.0 (see THIRD_PARTY_NOTICES.md).

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE = 'https://cdn.jsdelivr.net/npm/d3-celestial@0.7.35/data/stars.6.json'
const LIMIT_MAG = 5.5
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'shared', 'stars-catalog.js')
const check = process.argv.includes('--check')

const response = await fetch(SOURCE)
if (!response.ok) throw new Error(`fetch ${SOURCE} -> ${response.status}`)
const features = (await response.json()).features

const rows = []
for (const feature of features) {
  const mag = Number(feature.properties?.mag)
  if (!Number.isFinite(mag) || mag > LIMIT_MAG) continue
  let ra = Number(feature.geometry?.coordinates?.[0])
  const dec = Number(feature.geometry?.coordinates?.[1])
  if (!Number.isFinite(ra) || !Number.isFinite(dec)) continue
  // the source stores west-of-zero right ascension as a negative angle
  if (ra < 0) ra += 360
  const bv = Number.parseFloat(feature.properties?.bv)
  const colour = Number.isFinite(bv) ? Math.max(-0.4, Math.min(2.4, bv)) : 0.6
  rows.push([+ra.toFixed(2), +dec.toFixed(2), +mag.toFixed(2), +colour.toFixed(2)])
}
rows.sort((a, b) => a[2] - b[2])

const body = rows.map((row) => `[${row.join(',')}]`).join(',\n  ')
const text = `// Real naked-eye stars, magnitude <= ${LIMIT_MAG}, from d3-celestial 0.7.35
// (stars.6.json, HYG-derived, CC BY-SA 4.0 / see THIRD_PARTY_NOTICES.md).
// Each row is [rightAscensionDeg, declinationDeg, visualMagnitude, B-V index].
// RA is 0..360 here; the source file stores west-of-zero as a negative angle.
// Generated by scripts/gen-stars-catalog.mjs — do not edit by hand.
export const STAR_CATALOG = [
  ${body},
];
`

if (check) {
  let current = null
  try {
    current = await readFile(target, 'utf8')
  } catch {
    current = null
  }
  if (current !== text) {
    console.error('stars-catalog.js is stale: run node scripts/gen-stars-catalog.mjs')
    process.exit(1)
  }
  console.log(`ok      shared/stars-catalog.js (${rows.length} stars)`)
} else {
  await writeFile(target, text)
  console.log(`wrote   shared/stars-catalog.js (${rows.length} stars, ${Buffer.byteLength(text)} bytes)`)
}
